import pg from "pg";
import { logger } from "../lib/logger.js";

const { Pool } = pg;
let pool;

export async function connectDb(uri = process.env.DATABASE_URL) {
  if (pool) return pool;
  if (!uri) {
    throw new Error("DATABASE_URL is not set");
  }

  pool = new Pool({
    connectionString: uri,
    ssl: uri.includes("sslmode=require") ? { rejectUnauthorized: false } : undefined,
  });

  await pool.query(`
    create table if not exists public.users (
      id bigint generated by default as identity primary key,
      username text not null unique,
      password_hash text not null,
      created_at timestamptz not null default now(),
      updated_at timestamptz not null default now()
    );

    create table if not exists public.chats (
      id text primary key,
      user_id bigint not null references public.users(id) on delete cascade,
      title text not null,
      raw_query text not null default '',
      structured jsonb,
      constraint_mode text not null default 'heavy' check (constraint_mode in ('heavy', 'lite')),
      companies jsonb not null default '[]'::jsonb,
      cards jsonb not null default '[]'::jsonb,
      custom_columns jsonb not null default '[]'::jsonb,
      message text,
      created_at timestamptz not null default now(),
      updated_at timestamptz not null default now()
    );

    create index if not exists chats_user_updated_idx on public.chats (user_id, updated_at desc);
  `);

  await pool.query("select 1");
  logger.info("postgres_connected", { host: new URL(uri).hostname });
  return pool;
}

export function isDbConnected() {
  return Boolean(pool);
}

export function getDb() {
  if (!pool) throw new Error("Database is not connected");
  return pool;
}
